/* ==========================================================================
 * WindStrap utility generator
 * Produces the highly repetitive (but 1:1) Bootstrap → Tailwind classes:
 *   - src/generated/grid.css       (containers/cols/offsets/gutters)
 *   - src/generated/utilities.css  (base utility classes)
 *   - src/generated/responsive.css (sm/md/lg/xl/xxl utility variants)
 *
 * Every line is real CSS using Tailwind's @apply directive, so the output is
 * exactly what you would write by hand.
 * ========================================================================== */

const fs = require('fs');
const path = require('path');

const OUT = path.join(__dirname, '..', 'src', 'generated');
const TIERS = ['', 'sm', 'md', 'lg', 'xl', 'xxl'];
const pfx = (t) => (t ? `${t}-` : '');

const COL_WIDTHS = [
  8.33333333, 16.66666667, 25, 33.33333333, 41.66666667, 50,
  58.33333333, 66.66666667, 75, 83.33333333, 91.66666667, 100,
];

function fmtPct(n) {
  const s = String(n);
  return s.includes('.') ? `${s}%` : `${s}%`;
}

/* ------------------------------------------------------------------ grid */
function buildGrid() {
  const lines = [];
  lines.push('/* GENERATED by scripts/generate-utilities.js — grid system */');
  lines.push('');

  for (const t of TIERS) {
    const pre = pfx(t);
    const v = (util) => (t ? `${t}:${util}` : util);
    const colBase = t ? `col-${t}` : 'col';

    // .col (flex: 1 0 0%) and .col-auto
    lines.push(`.${colBase} { @apply ${v('flex-[1_0_0%]')}; }`);
    lines.push(`.${colBase}-auto { @apply ${v('w-auto')}; }`);

    // .col-1 … .col-12
    for (let i = 1; i <= 12; i++) {
      const w = fmtPct(COL_WIDTHS[i - 1]);
      lines.push(`.col-${pre}${i} { @apply ${v(`w-[${w}]`)}; }`);
    }

    // .row-cols-* > *
    for (let n = 1; n <= 6; n++) {
      const w = n === 1 ? '100%' : fmtPct(100 / n);
      lines.push(`.row-cols-${pre}${n} > * { flex: 0 0 auto; width: ${w}; }`);
    }
    lines.push(`.row-cols-${pre}auto > * { flex: 0 0 auto; width: auto; }`);

    // .offset-0 … .offset-11
    lines.push(`.offset-${pre}0 { @apply ${v('ms-0')}; }`);
    for (let i = 1; i <= 11; i++) {
      const w = fmtPct(COL_WIDTHS[i - 1]);
      lines.push(`.offset-${pre}${i} { @apply ${v(`ms-[${w}]`)}; }`);
    }

    // gutters g-* / gx-* / gy-*
    const gx = ['0px', '0.25rem', '0.5rem', '1rem', '1.5rem', '3rem'];
    for (let i = 0; i <= 5; i++) {
      lines.push(`.g-${pre}${i}, .gx-${pre}${i} { --bs-gutter-x: ${gx[i]}; }`);
      lines.push(`.g-${pre}${i}, .gy-${pre}${i} { --bs-gutter-y: ${gx[i]}; }`);
    }

    if (t !== '') lines.push('');
  }
  return lines.join('\n') + '\n';
}

